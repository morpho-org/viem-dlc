export type Corpus = { vaults: Address[]; live: boolean };

/**
 * Vault addresses, newest first from the API and falling back to {@link PINNED}. The page reports
 * which one it used, because a stale corpus changes the gas figures the tutorial talks about.
 */
export async function fetchCorpus(count: number): Promise<Corpus> {
  try {
    const res = await fetch(GRAPHQL_URL, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        query: `query ($chainIds: [Int!], $first: Int!) {
          vaultV2s(
            where: { chainId_in: $chainIds }
            orderBy: TotalAssetsUsd, orderDirection: Desc, first: $first
          ) { items { address } }
        }`,
        variables: { chainIds: [BASE_CHAIN_ID], first: Math.min(count, 100) },
      }),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const body = (await res.json()) as { data?: { vaultV2s: { items: { address: Address }[] } } };
    const items = body.data?.vaultV2s.items ?? [];
    if (items.length === 0) throw new Error("no vaults returned");
    // The API pages at 100; top up from the snapshot rather than making the reader wait on four more
    // round trips before anything runs.
    const live = items.map((item) => item.address);
    const seen = new Set(live.map((a) => a.toLowerCase()));
    for (const address of PINNED) {
      if (live.length >= count) break;
      if (!seen.has(address.toLowerCase())) live.push(address);
    }
    return { vaults: live.slice(0, count), live: true };
  } catch {
    return { vaults: PINNED.slice(0, count), live: false };
  }
}
